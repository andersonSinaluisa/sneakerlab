/**
 * Marca un PNG con su resolución física (chunk pHYs). Sin ella, los RIP de DTF y los editores
 * asumen 72 ppp y la pieza se imprimiría 4× más grande. canvas.toBlob no la escribe.
 */

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

export function crc32(bytes: Uint8Array): number {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

const PNG_SIG = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];

/** Inserta (o reemplaza) pHYs con `dpi` píxeles por pulgada. Devuelve un PNG nuevo. */
export function withPngDpi(png: Uint8Array, dpi: number): Uint8Array {
  if (!PNG_SIG.every((b, i) => png[i] === b)) throw new Error("No es un PNG");
  const ppm = Math.round(dpi / 0.0254);
  const chunk = new Uint8Array(21);
  const dv = new DataView(chunk.buffer);
  dv.setUint32(0, 9);
  chunk.set([0x70, 0x48, 0x59, 0x73], 4); // "pHYs"
  dv.setUint32(8, ppm);
  dv.setUint32(12, ppm);
  chunk[16] = 1; // unidad: metro
  dv.setUint32(17, crc32(chunk.subarray(4, 17)));

  // Recorre los chunks: copia todo menos un pHYs previo e inserta el nuevo tras IHDR.
  const parts: Uint8Array[] = [png.subarray(0, 8)];
  const view = new DataView(png.buffer, png.byteOffset, png.byteLength);
  let off = 8;
  while (off < png.length) {
    const len = view.getUint32(off);
    const type = String.fromCharCode(...png.subarray(off + 4, off + 8));
    const end = off + 12 + len;
    if (type !== "pHYs") parts.push(png.subarray(off, end));
    if (type === "IHDR") parts.push(chunk);
    off = end;
  }
  const out = new Uint8Array(parts.reduce((s, p) => s + p.length, 0));
  let o = 0;
  for (const p of parts) { out.set(p, o); o += p.length; }
  return out;
}

/** Lee la resolución de un PNG (ppp) o null si no la declara. */
export function readPngDpi(png: Uint8Array): number | null {
  const view = new DataView(png.buffer, png.byteOffset, png.byteLength);
  let off = 8;
  while (off < png.length) {
    const len = view.getUint32(off);
    const type = String.fromCharCode(...png.subarray(off + 4, off + 8));
    if (type === "pHYs" && png[off + 16] === 1) return Math.round(view.getUint32(off + 8) * 0.0254);
    off += 12 + len;
  }
  return null;
}
